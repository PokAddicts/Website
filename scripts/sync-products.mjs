// Pulls product data from a published Google Sheets CSV and writes
// src/data/products.generated.ts. Runs automatically before `dev` and `build`
// (see package.json), or on demand via `npm run sync-products`.
//
// Setup: publish your Sheet as CSV (File -> Share -> Publish to web -> CSV)
// and put the resulting URL in a .env file at the project root:
//   PRODUCTS_SHEET_CSV_URL=https://docs.google.com/spreadsheets/d/e/.../pub?output=csv
//
// Sheet columns (header row, exact names):
//   id, type, name, description, imageUrl, category, productType, price,
//   depositPercent, releaseDate, limitedQty, quantityAvailable
//
// - type: "preorder" or "stock"
// - category: one of pokemon-jp, pokemon-en, pokemon-kr, pokemon-cn, one-piece-en, one-piece-jp
// - depositPercent / releaseDate / limitedQty: preorder rows only
// - quantityAvailable: stock rows only
// - id, description, imageUrl: optional (id is auto-generated if left blank)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import Papa from "papaparse";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = resolve(__dirname, "../src/data/products.generated.ts");
const VALID_CATEGORIES = [
  "pokemon-jp",
  "pokemon-en",
  "pokemon-kr",
  "pokemon-cn",
  "one-piece-en",
  "one-piece-jp",
];

loadDotEnv(resolve(__dirname, "../.env"));

const sheetUrl = process.env.PRODUCTS_SHEET_CSV_URL;

async function main() {
  if (!sheetUrl) {
    console.warn(
      "[sync-products] PRODUCTS_SHEET_CSV_URL is not set — writing fallback sample data. " +
        "See scripts/sync-products.mjs for setup instructions."
    );
    writeGenerated(FALLBACK_PREORDERS, FALLBACK_STOCK);
    return;
  }

  let rows;
  try {
    const res = await fetch(sheetUrl);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const csvText = await res.text();
    rows = Papa.parse(csvText, { header: true, skipEmptyLines: true }).data;
  } catch (err) {
    console.warn(
      `[sync-products] Failed to fetch/parse the Sheet (${err.message}) — ` +
        (existsSync(OUTPUT_PATH)
          ? "keeping the last successfully synced data."
          : "writing fallback sample data.")
    );
    if (!existsSync(OUTPUT_PATH)) writeGenerated(FALLBACK_PREORDERS, FALLBACK_STOCK);
    return;
  }

  const preorders = [];
  const stock = [];
  let poCount = 0;
  let stCount = 0;
  let skipped = 0;

  for (const row of rows) {
    const type = (row.type || "").trim().toLowerCase();
    const name = (row.name || "").trim();
    const category = (row.category || "").trim();
    const price = Number(row.price);

    if (!name || !VALID_CATEGORIES.includes(category) || Number.isNaN(price)) {
      skipped++;
      console.warn(`[sync-products] Skipping row (missing/invalid name, category, or price): ${JSON.stringify(row)}`);
      continue;
    }

    const base = {
      id: (row.id || "").trim() || undefined,
      name,
      category,
      productType: (row.productType || "").trim(),
      price,
    };
    if ((row.description || "").trim()) base.description = row.description.trim();
    if ((row.imageUrl || "").trim()) base.imageUrl = row.imageUrl.trim();

    if (type === "preorder") {
      poCount++;
      preorders.push({
        ...base,
        id: base.id || `po-${poCount}`,
        depositPercent: Number(row.depositPercent) || 0,
        releaseDate: (row.releaseDate || "").trim(),
        ...(String(row.limitedQty).trim().toUpperCase() === "TRUE" ? { limitedQty: true } : {}),
      });
    } else if (type === "stock") {
      stCount++;
      stock.push({
        ...base,
        id: base.id || `st-${stCount}`,
        quantityAvailable: Number(row.quantityAvailable) || 0,
      });
    } else {
      skipped++;
      console.warn(`[sync-products] Skipping row (type must be "preorder" or "stock"): ${JSON.stringify(row)}`);
    }
  }

  if (preorders.length === 0 && stock.length === 0) {
    console.warn("[sync-products] No valid rows found — writing fallback sample data instead of an empty catalog.");
    writeGenerated(FALLBACK_PREORDERS, FALLBACK_STOCK);
    return;
  }

  writeGenerated(preorders, stock);
  console.log(
    `[sync-products] Synced ${preorders.length} preorder(s) and ${stock.length} stock item(s)` +
      (skipped ? ` (${skipped} row(s) skipped, see warnings above)` : "") +
      "."
  );
}

function writeGenerated(preorderProducts, stockProducts) {
  const header =
    "// AUTO-GENERATED by scripts/sync-products.mjs — do not edit by hand.\n" +
    "// Regenerate with `npm run sync-products` (also runs automatically before `dev`/`build`).\n" +
    'import type { PreorderProduct, StockProduct } from "./products";\n\n';

  const body =
    `export const preorderProducts: PreorderProduct[] = ${JSON.stringify(preorderProducts, null, 2)};\n\n` +
    `export const stockProducts: StockProduct[] = ${JSON.stringify(stockProducts, null, 2)};\n`;

  writeFileSync(OUTPUT_PATH, header + body);
}

function loadDotEnv(path) {
  if (!existsSync(path)) return;
  const text = readFileSync(path, "utf-8");
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, "");
    if (!(key in process.env)) process.env[key] = value;
  }
}

